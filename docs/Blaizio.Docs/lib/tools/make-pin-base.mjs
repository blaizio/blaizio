// Generates the /create theme-pin CSS. Two outputs, both gitignored:
//
//   Styles/skins/style-<name>.css  - each skin donut-holed: every rule's subject gets
//                                    `:where(:not(.bz-theme-base *))` appended, so skin rules
//                                    structurally CANNOT match inside a pinned subtree. Crucial
//                                    because a skin may set properties (uppercase titles,
//                                    letter-spacing, shadows) the default skin never declares, so
//                                    no amount of override layering could undo them. `:where()`
//                                    adds zero specificity, and unlike an `@scope` donut it keeps
//                                    responsive/dark variants working (Chromium does not evaluate
//                                    `@media` nested inside `@scope`).
//   Styles/pin-base.css            - the ember (default) skin rescoped under .bz-theme-base,
//                                    giving the pinned subtree its structure back. Colors come
//                                    from tokens.css's .bz-theme-base var blocks.
//
// The /themes page pins its control surface (rail, dialogs, toasts) this way while the canvas
// re-skins live. Generated from the real skin files so the pin can never drift. Runs from
// `pnpm run build:css` / `watch:css` and the csproj's BuildDocsTailwind target.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const docsDir = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const srcStyles = join(docsDir, '..', '..', 'src', 'Blaizio.Ui', 'Styles');
const outSkins = join(docsDir, 'Styles', 'skins');
mkdirSync(outSkins, { recursive: true });

const skins = ['ember', 'spark', 'glow', 'forge', 'flint', 'aura', 'ash', 'wisp'];
const HOLE = ':where(:not(.bz-theme-base *))';

const banner = (what) => `/*\n  GENERATED by lib/tools/make-pin-base.mjs - DO NOT EDIT.\n  ${what}\n*/\n`;

/** A skin file's body without its own header comment. */
const bodyOf = (name) =>
  readFileSync(join(srcStyles, `style-${name}.css`), 'utf8').replace(/^\/\*[\s\S]*?\*\/\s*/, '');

/** Append the donut hole to one selector's subject (before any pseudo-element). */
function holed(selector) {
  const sel = selector.trim();
  const pe = sel.indexOf('::');
  return pe >= 0 ? sel.slice(0, pe) + HOLE + sel.slice(pe) : sel + HOLE;
}

for (const name of skins) {
  const root = postcss.parse(bodyOf(name));
  const wrapper = `.style-${name}`;
  root.walkRules((rule) => {
    if (rule.selector === wrapper) return; // the scope root itself stays untouched
    rule.selectors = rule.selectors.map(holed);
  });
  writeFileSync(
    join(outSkins, `style-${name}.css`),
    banner(`The ${name} skin donut-holed so it never applies inside a .bz-theme-base subtree.`) +
      root.toString(),
  );
}

writeFileSync(
  join(docsDir, 'Styles', 'pin-base.css'),
  banner(
    'The ember (default) skin rescoped under .bz-theme-base - the structure a pinned subtree\n' +
      "  (the /create rail, its dialogs and toasts) keeps no matter which skin sits on <html>.",
  ) + bodyOf('ember').replaceAll('.style-ember', '.bz-theme-base'),
);

console.log(`generated ${skins.length} donut-holed skins + pin-base.css`);
